def scores(values: dict) -> dict:
    """The scoring rules of proposals/scoring_rules.txt."""
    low_price = min(v[0] for v in values.values())
    fast = min(v[2] for v in values.values())
    out = {}
    for b, (price, met, days, years, judge) in values.items():
        parts = [100 * low_price / price, 100 * met / 8, 100 * fast / days, min(100, 100 * years / 5), 100 * judge / 5]
        out[b] = {"parts": [round(x, 2) for x in parts],
                  "total": round(sum(w * x for (_, _, w), x in zip(WEIGHTS, parts)) / 100, 2)}
    return out


def transcript(title: str, note: str, head: str, lines) -> str:
    return f"{title}\n{note}\n{head}\n\n" + "\n".join(f"[{t}] {who}: {said}" for t, who, said in lines)


def page(n: int, total: int, body: str, en: bool = False) -> str:
    mark = f"===== Page {n} of {total} =====" if en else f"===== صفحة {n} من {total} ====="
    return f"{mark}\n{body.strip()}\n"


