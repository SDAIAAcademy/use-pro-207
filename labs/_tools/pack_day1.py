def money(x: float) -> str:
    return f"{x:,.0f}"


def quotes():
    out = []
    for i in range(3):
        lines = [(n, u, q, p[i], q * p[i]) for n, u, q, p in QUOTE_LINES]
        sub = sum(x[4] for x in lines)
        out.append({"supplier": QUOTE_SUPPLIERS[i], "lines": lines, "subtotal": sub,
                    "vat": round(sub * VAT), "total": round(sub * (1 + VAT))})
    return out


